-- 1. Create Notifications Table
CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT DEFAULT 'info', -- 'update', 'reward', 'system', 'social'
    is_read BOOLEAN DEFAULT FALSE,
    link TEXT, -- Optional link to redirect (e.g., /webtoon/1/read/5)
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- RLS Policies
DROP POLICY IF EXISTS "Users can view their own notifications" ON public.notifications;
CREATE POLICY "Users can view their own notifications" 
ON public.notifications FOR SELECT 
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own notifications" ON public.notifications;
CREATE POLICY "Users can update their own notifications" 
ON public.notifications FOR UPDATE 
USING (auth.uid() = user_id);

-- 2. Trigger: Notify followers on new chapter
CREATE OR REPLACE FUNCTION public.notify_new_chapter()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.notifications (user_id, title, message, type, link)
    SELECT 
        b.user_id,
        'Шинэ бүлэг орлоо!',
        w.title || ' - ' || NEW.title || ' амжилттай нэмэгдлээ.',
        'update',
        '/webtoon/' || NEW.webtoon_id || '/read/' || NEW.id
    FROM public.bookmarks b
    JOIN public.webtoons w ON w.id = b.webtoon_id
    WHERE b.webtoon_id = NEW.webtoon_id;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS tr_notify_new_chapter ON public.chapters;
CREATE TRIGGER tr_notify_new_chapter
    AFTER INSERT ON public.chapters
    FOR EACH ROW EXECUTE PROCEDURE public.notify_new_chapter();

